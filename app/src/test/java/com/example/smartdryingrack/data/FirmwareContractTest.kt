package com.example.smartdryingrack.data

import com.example.smartdryingrack.data.hardware.rest.*
import com.example.smartdryingrack.domain.model.*
import kotlinx.coroutines.runBlocking
import okhttp3.mockwebserver.MockResponse
import okhttp3.mockwebserver.MockWebServer
import org.json.JSONObject
import org.junit.Assert.*
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config
import java.net.HttpURLConnection
import java.net.InetAddress
import java.net.URL

@RunWith(RobolectricTestRunner::class)
@Config(manifest = Config.NONE, sdk = [28])
class FirmwareContractTest {
    // Generated by contract_export_test.cpp using the real sketch and ArduinoJson.
    private fun responses() = JSONObject(javaClass.getResource("/firmware-contract-v1.1.7.json")!!.readText())

    @Test fun actualFirmwareResponsesWorkWithAppHttpClientsAndAndroidJson() = runBlocking {
        val payloads = responses()
        val server = MockWebServer()
        server.start(InetAddress.getByName("127.0.0.1"), 0)
        val factory = { url: URL -> URL("http://127.0.0.1:${server.port}${url.path}").openConnection() as HttpURLConnection }
        val rack = RackApi(factory); val lights = LightingApi(factory)
        val address = "http://192.168.1.50:${server.port}"
        fun reply(name: String) { server.enqueue(MockResponse().setBody(payloads.getJSONObject(name).toString())) }
        try {
            reply("manualMutedStatus")
            val manual = rack.status(address)
            assertEquals(RackMode.MANUAL, manual.mode)
            assertEquals(false, manual.buzzerEnabled)
            assertEquals(true, manual.buzzerAvailable)
            reply("autoConfig"); assertEquals(RackMode.AUTO, rack.setMode(address, RackMode.AUTO))
            reply("autoMutedPreferenceStatus")
            val auto = rack.status(address)
            assertEquals(RackMode.AUTO, auto.mode)
            assertEquals(false, auto.buzzerEnabled) // Retained preference is not AUTO's effective permission.
            assertEquals(true, auto.buzzerAutoRequired)
            assertTrue(payloads.getJSONObject("autoMutedPreferenceStatus").getBoolean("buzzerEffectiveEnabled"))
            reply("manualConfig"); assertEquals(RackMode.MANUAL, rack.setMode(address, RackMode.MANUAL))
            reply("buzzerEnableAck"); assertTrue(rack.setBuzzer(address, true))
            reply("manualEnabledStatus"); assertEquals(true, rack.status(address).buzzerEnabled)
            reply("movementAck"); rack.command(address, "EXTEND")
            reply("lightsBefore"); val before = lights.fetch(address)
            assertEquals(true, before.indicatorHardwareEnabled)
            assertEquals("RACK_MOVING", before.indicator!!.meaning)
            val zone = LightingZone.FRONT
            reply("lightAck")
            val ack = lights.update(address, LightingUpdate(zone, before.deviceSession,
                before.zones.getValue(zone).revision, "contract-front", LightSettings(true, 25)))
            reply("lightsAfter"); val confirmed = lights.fetch(address)
            assertEquals(ack.revision, confirmed.zones.getValue(zone).revision)
            assertEquals("contract-front", confirmed.zones.getValue(zone).lastRequestId)
            assertEquals(LightSettings(true, 25), confirmed.zones.getValue(zone).settings)
            assertEquals(before.indicator, confirmed.indicator)
            LightingZone.entries.filter { it != zone }.forEach { assertEquals(before.zones[it], confirmed.zones[it]) }
            assertEquals(10, server.requestCount)
        } finally { server.shutdown() }
    }

    @Test fun missingAvailabilityIsUnknownAndInvalidAvailabilityIsRejected() {
        val json = responses().getJSONObject("manualEnabledStatus")
        json.remove("buzzerAvailable")
        assertNull(parseRackSnapshot(json.toString(), 1).buzzerAvailable)
        json.put("buzzerAvailable", "true")
        assertThrows(IllegalArgumentException::class.java) { parseRackSnapshot(json.toString(), 1) }
    }
}
